#!/usr/bin/env node
/*
 * Builds js/data/srd-content.js from the SRD 5.2 (2024) XML files in the
 * FightClub5eXML project (https://github.com/vidalvanbergen/FightClub5eXML, MIT).
 *
 *   node tools/build-srd.js /path/to/FightClub5eXML
 *
 * Only spells, items, magic items and creatures are bundled; the classes, species,
 * backgrounds and feats of the SRD are already built into the app with full mechanics.
 */
const fs = require('fs');
const path = require('path');
require(path.join(__dirname, '..', 'js', 'fc5.js'));
const FC5 = globalThis.DND.FC5;

const repo = process.argv[2];
if (!repo) { console.error('Usage: node tools/build-srd.js /path/to/FightClub5eXML'); process.exit(1); }
const dir = path.join(repo, 'Sources', 'System_Reference_Document_DND_5.5e');
const files = ['default_spells_5.5e.xml', 'default_items_5.5e.xml', 'default_magic_items-5.5e.xml', 'default_bestiary_5.5e.xml'];

let data = FC5.emptyData();
for (const f of files) FC5.parse(fs.readFileSync(path.join(dir, f), 'utf8'), data);
data = FC5.dedupe(data);
const out = { spells: data.spells, items: data.items, monsters: data.monsters };

const header = `/*
 * SRD 5.2 content: spells, items, magic items and creatures.
 * Generated by tools/build-srd.js from the FightClub5eXML project (MIT License,
 * https://github.com/vidalvanbergen/FightClub5eXML). Do not edit by hand.
 *
 * This work includes material from the System Reference Document 5.2 ("SRD 5.2") by
 * Wizards of the Coast LLC, available at https://www.dndbeyond.com/srd. The SRD 5.2 is
 * licensed under the Creative Commons Attribution 4.0 International License, available at
 * https://creativecommons.org/licenses/by/4.0/legalcode.
 */
`;
const target = path.join(__dirname, '..', 'js', 'data', 'srd-content.js');
fs.writeFileSync(target, header + '(typeof window !== "undefined" ? window : globalThis).DND_SRD_CONTENT = ' + JSON.stringify(out) + ';\n');
console.log('Wrote', target, Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])), (fs.statSync(target).size / 1e6).toFixed(2) + ' MB');
